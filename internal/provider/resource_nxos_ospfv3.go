func (r *OSPFv3Resource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan OSPFv3ResourceModel

	// Read plan
	diags := req.Plan.Get(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Read config
	var config OSPFv3ResourceModel
	diags = req.Config.Get(ctx, &config)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Debug(ctx, fmt.Sprintf("%s: Beginning Create", plan.getDn()))

	device, ok := r.data.Devices[plan.Device.ValueString()]
	if !ok {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to find device '%s' in provider configuration", plan.Device.ValueString()))
		return
	}

	// Post object
	var preexisting map[string]bool
	if device.Managed {
		body := plan.toBody(config.OSPFv3)
		resp.Diagnostics.Append(helpers.CheckMinVersion(ctx, device.Client, plan.Device.ValueString(), body.Str, OSPFv3MinVersions)...)
		if resp.Diagnostics.HasError() {
			return
		}
		// Record which of the managed objects already exist, for the reset deletion policy
		res, err := getOSPFv3Tree(ctx, device, plan.getDn())
		if err != nil {
			resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to retrieve object, got error: %s", err))
			return
		}
		preexisting = helpers.FilterExisting(plan.managedDns(), helpers.ReadTree(res, plan.getDn()).Dns())
		_, err = device.Client.Post(plan.getDn(), body.Str)
		if err != nil {
			resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to post object, got error: %s", err))
			return
		}
	}

	plan.Dn = types.StringValue(plan.getDn())
	var identity OSPFv3Identity
	identity.toIdentity(ctx, &plan.OSPFv3)

	tflog.Debug(ctx, fmt.Sprintf("%s: Create finished successfully", plan.getDn()))

	diags = resp.State.Set(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	diags = resp.Identity.Set(ctx, &identity)
	resp.Diagnostics.Append(diags...)

	if preexisting != nil {
		helpers.SetPreexisting(ctx, resp.Private, preexisting, &resp.Diagnostics)
	}
	helpers.SetFlagImporting(ctx, false, resp.Private, &resp.Diagnostics)
}

