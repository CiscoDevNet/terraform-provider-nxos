func (r *DefaultQoSResource) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.Plan.Raw.IsNull() {
		return
	}

	// The check is skipped if the plan cannot be fully evaluated yet (e.g. unknown map keys or device);
	// Create and Update repeat it before sending the request.
	if len(DefaultQoSMinVersions) > 0 && r.data != nil {
		var plan, config DefaultQoSResourceModel
		if !req.Plan.Get(ctx, &plan).HasError() && !req.Config.Get(ctx, &config).HasError() && !plan.Device.IsUnknown() {
			if device, ok := r.data.Devices[plan.Device.ValueString()]; ok && device.Managed {
				resp.Diagnostics.Append(helpers.CheckMinVersion(ctx, device.Client, plan.Device.ValueString(), plan.toBody(config.DefaultQoS).Str, DefaultQoSMinVersions)...)
				if resp.Diagnostics.HasError() {
					return
				}
			}
		}
	}

	if req.State.Raw.IsNull() {
		return
	}

	imp, diags := helpers.IsFlagImporting(ctx, req.Private)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() || !imp {
		return
	}

	resp.Diagnostics.Append(resp.Plan.SetAttribute(ctx, path.Root("id"), types.StringUnknown())...)
}

