func (r *ESGResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var state ESG

	// Read state
	diags := req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Read identity if available (requires Terraform >= 1.12.0)
	if req.Identity != nil && !req.Identity.Raw.IsNull() {
		var identity ESGIdentity
		diags = req.Identity.Get(ctx, &identity)
		if resp.Diagnostics.Append(diags...); resp.Diagnostics.HasError() {
			return
		}
		state.fromIdentity(ctx, &identity)
	}

	tflog.Debug(ctx, fmt.Sprintf("%s: Beginning Read", state.Dn.ValueString()))

	device, ok := r.data.Devices[state.Device.ValueString()]
	if !ok {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to find device '%s' in provider configuration", state.Device.ValueString()))
		return
	}

	if device.Managed {
		res, err := device.GetSubtree(ctx, state.Dn.ValueString(), []string{"esgGroupEntity", "esgGroupInst", "esgSelectorEntity", "esgMatchConnectedEpV4", "esgMatchConnectedEpV6", "esgMatchVlan", "esgMatchExternalSubnetV4", "esgMatchExternalSubnetV6", "esgMatchExternalSubnetV4WithNh", "esgMatchExternalSubnetV6WithNh", "esgMatchExternalSubnetV4WithNhEncap", "esgMatchExternalSubnetV6WithNhEncap", "esgMatchInterface", "esgMatchVlanMac", "esgMatchVlanInterface", "esgAttributeEntity", "esgClassMapEntity", "esgClassMapInst", "esgClassMapFilterEntry", "esgPolicyMapEntity", "esgPolicyMapInst", "esgMatchClassMap", "esgDom", "esgContractEntity", "esgContract"}, ESGSubtreeClassMinVersions)
		if err != nil {
			resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to retrieve object, got error: %s", err))
			return
		}

		if !res.Exists() {
			resp.State.RemoveResource(ctx)
			return
		}

		imp, diags := helpers.IsFlagImporting(ctx, req.Private)
		if resp.Diagnostics.Append(diags...); resp.Diagnostics.HasError() {
			return
		}
		if imp {
			state.fromBody(res)
			// Warn here rather than in ModifyPlan: Terraform reuses this same refresh for both the
			// preview plan and the plan it recomputes right before applying, so Read only runs once
			// per operation - unlike ModifyPlan, which runs (and would warn) twice.
			resp.Diagnostics.AddWarning(
				"Import leniency in effect",
				"This resource was recently imported. If the plan shows entries or attributes disappearing, "+
					"that's expected: Terraform will stop tracking anything not declared in your configuration, "+
					"but nothing will change on the device. This notice won't appear again after your next apply.",
			)
		} else {
			state.updateFromBody(res)
		}
	}

	var identity ESGIdentity
	identity.toIdentity(ctx, &state)

	tflog.Debug(ctx, fmt.Sprintf("%s: Read finished successfully", state.Dn.ValueString()))

	diags = resp.State.Set(ctx, &state)
	resp.Diagnostics.Append(diags...)
	diags = resp.Identity.Set(ctx, &identity)
	resp.Diagnostics.Append(diags...)
}

