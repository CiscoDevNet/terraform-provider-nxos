func (r *DefaultQoSResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan DefaultQoSResourceModel

	// Read plan
	diags := req.Plan.Get(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	// Read config
	var config DefaultQoSResourceModel
	diags = req.Config.Get(ctx, &config)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	var state DefaultQoSResourceModel

	// Read state
	diags = req.State.Get(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Debug(ctx, fmt.Sprintf("%s: Beginning Update", plan.getDn()))

	device, ok := r.data.Devices[plan.Device.ValueString()]
	if !ok {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to find device '%s' in provider configuration", plan.Device.ValueString()))
		return
	}

	imp, diags := helpers.IsFlagImporting(ctx, req.Private)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	var preexisting map[string]bool
	if device.Managed {
		// Keep track of which managed objects already existed, for the reset deletion policy. State written
		// before this was recorded has an unknown history, so all of its objects are assumed to have existed.
		preexisting, diags = helpers.GetPreexisting(ctx, req.Private)
		if resp.Diagnostics.Append(diags...); resp.Diagnostics.HasError() {
			return
		}
		stateDns := state.managedDns()
		if preexisting == nil {
			preexisting = maps.Clone(stateDns)
		}
		planDns := plan.managedDns()
		added := map[string]bool{}
		for dn := range planDns {
			if !stateDns[dn] {
				added[dn] = true
			}
		}
		removed := false
		for dn := range stateDns {
			if !planDns[dn] {
				removed = true
				break
			}
		}
		deletePolicy := r.deletionPolicy(plan.DeletionPolicy) == "delete"
		var tree helpers.Tree
		if len(added) > 0 || (deletePolicy && removed) {
			res, err := getDefaultQoSTree(ctx, device, plan.getDn())
			if err != nil {
				resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to retrieve object, got error: %s", err))
				return
			}
			tree = helpers.ReadTree(res, plan.getDn())
		}
		for dn := range helpers.FilterExisting(added, tree.Dns()) {
			preexisting[dn] = true
		}
		// Objects no longer managed are forgotten, they are deleted or reset by this update
		preexisting = helpers.FilterExisting(preexisting, planDns)
		// With the delete policy, single child objects without configured attributes or children are deleted,
		// unless the device holds list entries below them that are not managed by the resource
		var deleteEmptied func(dn string) bool
		if deletePolicy && removed {
			deleteEmptied = func(dn string) bool { return !tree.HasUnmanagedEntries(dn, stateDns, DefaultQoSListClasses) }
		}
		body := plan.toBodyWithDeletes(ctx, state.DefaultQoS, config.DefaultQoS, imp, deleteEmptied)
		resp.Diagnostics.Append(helpers.CheckMinVersion(ctx, device.Client, plan.Device.ValueString(), body.Str, DefaultQoSMinVersions)...)
		if resp.Diagnostics.HasError() {
			return
		}
		_, err := device.Client.Post(plan.getDn(), body.Str)
		if err != nil {
			resp.Diagnostics.AddError("Client Error", fmt.Sprintf("Failed to update object, got error: %s", err))
			return
		}
	}

	plan.Dn = types.StringValue(plan.getDn())
	var identity DefaultQoSIdentity
	identity.toIdentity(ctx, &plan.DefaultQoS)

	tflog.Debug(ctx, fmt.Sprintf("%s: Update finished successfully", plan.getDn()))

	diags = resp.State.Set(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	diags = resp.Identity.Set(ctx, &identity)
	resp.Diagnostics.Append(diags...)

	if preexisting != nil {
		helpers.SetPreexisting(ctx, resp.Private, preexisting, &resp.Diagnostics)
	}

	helpers.SetFlagImporting(ctx, false, resp.Private, &resp.Diagnostics)
}

